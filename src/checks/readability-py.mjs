// Q4 的 Python 分支（2026-11-17，解除纯 Python 仓的 Q4 语言缺口）。
//
// 为什么单独一个模块：`analyzeFile` 是 Babel AST 驱动（Node 对象、loc、forEachChild），
// Python 没有 AST 可用（产品要零依赖跑在客户机上）。混进同一个函数会让两条路径
// 互相污染——JS 规则被 Python 的缩进逻辑影响、Python 规则被 Babel 节点类型绊住。
//
// 复用 `py-structure.mjs` 的结构解析（缩进 + 词法状态机），映射到与 JS 侧**同一套
// rule id / 阈值 / 严重度**，这样报告口径不需要两套解释：
//   Q4.fn-length      函数体行数 > maxFunctionLines / hardFunctionLines
//   Q4.nesting-depth  函数内块关键字（if/for/while/try/with/match/case）嵌套 > maxNesting
//   Q4.comment-density  ≥commentMinFileLines 行且注释行占比 < commentMinRatio
//   Q4.magic-number   同一函数内非豁免字面量数字 ≥ magicNumberCount
//   Q4.naming         单字母/无信息词变量名、单字符函数名
//
// 明确**不**做（写在 coverageGap/warnings 里，不冒充已查）：
//   · duplicate-string / ts-any / ts-ignore：Python 侧没有对应语义（不做就是不做）

import path from 'node:path';
import { parsePyStructure, indentOf } from '../py-structure.mjs';

// 与 JS 侧同一份豁免口径：0/1/-1/2/100/1000 不算魔法数
const EXEMPT_NUMBERS = new Set([0, 1, -1, 2, 100, 1000]);
// 尺寸/时间类命名（与 JS 侧 SIZE_TIME_NAMES 同义）
const SIZE_TIME_NAMES = /(?:timeout|delay|interval|ms|secs?|seconds?|minutes?|hours?|days?|width|height|size|length|bytes|kb|mb|gb|percent|ratio|port|retries|attempts|limit|max|min)/i;
// 单字母/无信息词（与 JS 侧 NAMING_ALLOWED / NAMING_NOISE 同口径）
const NAMING_ALLOWED = new Set(['i', 'j', 'k', 'n', 'x', 'y', 'z', 'r', 'g', 'b', 'a', '_', 'e', 'q', 's', 't', 'u', 'v', 'w']);
const NAMING_NOISE = new Set(['data', 'temp', 'tmp', 'foo', 'bar', 'baz', 'val', 'value', 'res', 'result', 'obj', 'object', 'item', 'items', 'x1', 'x2']);
const BLOCK_KEYWORDS = /^(?:if|elif|else|for|while|try|except|finally|with|match|case)\b/;
// 赋值语句：`name = ...` / `name: Type = ...` / 元组解包 `a, b = ...`
const ASSIGN_RE = /^(?:[\w.,\s*()]+?)\s*(?::\s*[\w\[\], .|]+)?\s*=\s*(?!=)/;
const NAME_CANDIDATE_RE = /^([A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)*)\s*(?::[^=]*)?=/;

/** 数字字面量（排除字符串、标识符里的数字、属性访问 `.0` 这类） */
const NUMBER_RE = /(?<![A-Za-z0-9_.])(-?\d+(?:\.\d+)?)(?![A-Za-z0-9_])/g;

function stripComment(line) {
  // Python 注释用 #；但 # 可能出现在字符串里，这里用最保守的做法：
  // 只当 `#` 前面没有引号时才认为它开始注释（py-structure 已把三引号抹掉）。
  const code = String(line || '');
  const q1 = code.indexOf("'");
  const q2 = code.indexOf('"');
  const hash = code.indexOf('#');
  if (hash < 0) return code;
  const firstQuote = [q1, q2].filter((i) => i >= 0).reduce((a, b) => Math.min(a, b), Infinity);
  if (firstQuote < hash) return code; // # 在字符串里（粗略判断，宁可漏判不当成注释）
  return code.slice(0, hash);
}

/** 是否豁免数字（尺寸/时间命名上下文里出现的数字不算魔法数，与 JS 侧同义） */
function isExemptNumber(raw, contextLine) {
  const v = Number(raw);
  if (EXEMPT_NUMBERS.has(v)) return true;
  if (SIZE_TIME_NAMES.test(contextLine)) return true;
  // HTTP 状态码：`status_code=404` / `HTTPException(400)` 是协议常量，不是业务魔法数。
  // 不过滤会让每个错误分支都报一条（fastapi 实跑：payment.py 一个函数报 3 条全是 400/503）。
  if (/status(?:_code)?\s*[=:]|HTTPException\s*\(/.test(contextLine)) return true;
  return false;
}

/**
 * 分析一个 Python 文件，产出的 finding 与 JS 侧同形（rule/line/snippet/message）。
 * @param {object} opts
 * @param {string} opts.file 相对路径
 * @param {string} opts.text 源码
 * @param {object} opts.thresholds 与 JS 侧同一份阈值对象
 * @param {function} opts.emit (rule, severity, line, message, snippet) => void
 * @param {function} opts.snip (line:number) => string 取该行脱敏片段
 * @returns {{ skippedGenerated:boolean, unsupported:string[] }}
 */
export function analyzePyFile({ file, text, thresholds, emit, snip }) {
  const lines = String(text).replace(/\r\n?/g, '\n').split('\n');
  if (lines.length && lines[lines.length - 1] === '') lines.pop();
  // 生成代码探测（与 JS 侧的 detectHeader 同义但口径更窄：只看头部标记）
  const head = lines.slice(0, 6).join('\n').toLowerCase();
  const generated = /\b(auto-generated|autogenerated|do not edit|@generated|generated by)\b/.test(head);
  const st = parsePyStructure(text);
  const unsupported = [];

  // ── 规则 3：注释密度（放最前面，与 JS 侧顺序一致；不影响结论）
  if (!generated && lines.length >= thresholds.commentMinFileLines) {
    const commentLines = st.commentLines;
    const ratio = commentLines / lines.length;
    if (ratio < thresholds.commentMinRatio) {
      emit('Q4.comment-density', 'low', 1,
        `注释密度过低：${lines.length} 行文件仅 ${commentLines} 行注释（${(ratio * 100).toFixed(1)}% < ${(thresholds.commentMinRatio * 100).toFixed(1)}%），建议补关键决策说明`,
        snip(1));
    }
  }

  // ── 规则 1 + 2 + 4：按函数
  for (const fn of st.functions) {
    const length = fn.end - fn.start + 1;
    if (length > thresholds.hardFunctionLines) {
      emit('Q4.fn-length', 'medium', fn.start,
        `函数 ${fn.name} 过长：${length} 行（中危阈值 ${thresholds.hardFunctionLines}），失控风险高，建议拆分`,
        snip(fn.start));
    } else if (length > thresholds.maxFunctionLines) {
      emit('Q4.fn-length', 'low', fn.start,
        `函数 ${fn.name} 过长：${length} 行（提醒阈值 ${thresholds.maxFunctionLines}），建议按职责拆分`,
        snip(fn.start));
    }

    // 嵌套：py-structure 已按「块关键字 + 缩进层数」算出 maxDepth 与最深行
    if (fn.maxDepth > thresholds.maxNesting) {
      const deepest = Number(fn.deepestLine) || findDeepestBlockLine(lines, fn) || fn.start;
      emit('Q4.nesting-depth', 'low', deepest,
        `控制流嵌套 ${fn.maxDepth} 层（上限 ${thresholds.maxNesting}），建议用早返回/提取函数压平`,
        snip(deepest));
    }

    // 魔法数：只扫函数体，跳过注释与字符串
    const numbers = [];
    for (let i = fn.start; i <= fn.end; i++) {
      const code = stripComment(lines[i - 1] || '');
      NUMBER_RE.lastIndex = 0;
      let m;
      while ((m = NUMBER_RE.exec(code)) !== null) {
        if (!isExemptNumber(m[1], code)) numbers.push({ value: m[1], line: i });
      }
    }
    if (numbers.length >= thresholds.magicNumberCount) {
      const unique = [...new Set(numbers.map((n) => n.value))].slice(0, 6).join('、');
      emit('Q4.magic-number', 'low', numbers[0].line,
        `函数 ${fn.name} 内有 ${numbers.length} 个字面量数字（${unique} …），建议提成有名字的常量`,
        snip(numbers[0].line));
    }
  }

  // ── 规则 5：命名
  // Python 的变量声明就是赋值语句；只看模块级与函数内的「简单名目标」，解包占位不报。
  for (let i = 1; i <= lines.length; i++) {
    const raw = lines[i - 1] || '';
    const code = stripComment(raw).trim();
    if (!code || code.startsWith('#')) continue;
    if (!ASSIGN_RE.test(code)) continue;
    const m = NAME_CANDIDATE_RE.exec(code);
    if (!m) continue;
    // 参数默认值那种 `x=1` 在调用里也会命中，但 ASSIGN_RE 排除了 `==`；这里再排除「括号内」的调用参数
    const openParen = code.lastIndexOf('(', code.indexOf('='));
    const closeParen = code.indexOf(')');
    if (openParen >= 0 && (closeParen < 0 || closeParen > openParen)) continue;
    const names = m[1].split(',').map((s) => s.trim().replace(/^\*+/, '')).filter(Boolean);
    for (const name of names) {
      if (!name || name === '_') continue; // `_ = ...` 约定忽略
      const single = name.length === 1;
      const lower = name.toLowerCase();
      if (single && NAMING_ALLOWED.has(lower)) continue; // 循环/坐标约定
      if (NAME_LIKE_CONSTANT.test(name)) continue; // 全大写常量不报
      if (upperSingle(name)) continue; // 单个大写字母视为常量/类
      if (single) {
        emit('Q4.naming', 'low', i, `变量 ${name} 看不出用途，建议改成能读懂用途的名字`, snip(i));
      } else if (NAMING_NOISE.has(lower)) {
        emit('Q4.naming', 'low', i, `变量 ${name} 无信息量（data/temp/foo 这类名字看不出用途），建议改成能读懂用途的名字`, snip(i));
      }
    }
  }
  // 单字符函数名
  for (const fn of st.functions) {
    const name = fn.name || '';
    if (name.length !== 1) continue;
    if (name === '_' || NAMING_ALLOWED.has(name.toLowerCase())) continue;
    if (upperSingle(name)) continue;
    emit('Q4.naming', 'low', fn.start, `函数 ${name} 是单字符名，看不出用途，建议改成能读懂用途的名字`, snip(fn.start));
  }

  // 不做项显式声明（fail-closed：说清没查，不冒充已查）
  unsupported.push('Q4.duplicate-string：Python 侧不做字符串字面量重复检测（f-string/拼接语义与 JS 不同）');
  return { skippedGenerated: generated, unsupported };
}

const NAME_LIKE_CONSTANT = /^[A-Z][A-Z0-9_]{1,}$/;
function upperSingle(name) { return /^[A-Z]$/.test(name); }

// 后备：py-structure 没给 deepestLine 时，自己找第一个「块关键字 + 更深缩进」的行
function findDeepestBlockLine(lines, fn) {
  const baseIndent = indentOf(lines[fn.start - 1] || '');
  let best = 0;
  let bestIndent = baseIndent;
  for (let i = fn.start + 1; i <= fn.end; i++) {
    const l = lines[i - 1] || '';
    const ind = indentOf(l);
    if (ind > bestIndent && BLOCK_KEYWORDS.test(l.trim())) { best = i; bestIndent = ind; }
  }
  return best;
}

/** Python 文件是否值得进 Q4（除了 .py 还有别的门槛吗？目前没有——docstring 由 py-structure 抹掉） */
export function isPySource(ext) {
  return String(ext || '').toLowerCase() === '.py';
}

/** 相对路径判断（供调用方在需要时区分） */
export function pyRelOf(root, abs) {
  return path.relative(root, abs).replace(/\\/g, '/');
}
